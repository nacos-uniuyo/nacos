async function main() {
  await db.delete(project);
  await db.delete(opportunity);

  const [users, departments, sessions] = await Promise.all([
    db.select({ id: user.id }).from(user).limit(20),
    db.select({ id: department.id, slug: department.slug }).from(department),
    db.select({ id: schoolSession.id, slug: schoolSession.slug }).from(schoolSession),
  ]);

  if (users.length === 0) throw new Error("No users found. Create at least one user before seeding.");
  if (departments.length === 0) throw new Error("No departments found.");

  const departmentBySlug = new Map(departments.map((d) => [d.slug, d.id]));
  const sessionBySlug = new Map(sessions.map((s) => [s.slug, s.id]));

  const projectRows = projectSeeds.map((seed, index) => {
    const departmentId = departmentBySlug.get(seed.departmentSlug);
    if (!departmentId) throw new Error(`Unknown department slug: ${seed.departmentSlug}`);
    const sessionId = seed.sessionSlug ? sessionBySlug.get(seed.sessionSlug) ?? null : null;
    const authorUserId = users[index % users.length].id;
    const slug = `seed-${slugify(seed.title)}`.slice(0, 128);

    return {
      slug,
      title: seed.title,
      tagline: seed.tagline,
      descriptionJson: doc(...seed.description),
      departmentId,
      sessionId,
      category: seed.category,
      courseCode: seed.courseCode ?? null,
      cohortGroupNumber: null,
      teamDisplayName: seed.teamDisplayName ?? null,
      leadContributors: seed.leadContributors,
      status: seed.status,
      rejectionReason: seed.rejectionReason ?? null,
      authorUserId,
      bannerUrl: seed.image,
      bannerPublicId: null,
      galleryUrls: [],
      repoUrl: seed.repoUrl ?? null,
      demoUrl: seed.demoUrl ?? null,
      featured: seed.featured ?? false,
    };
  });

  const opportunityRows = opportunitySeeds.map((seed, index) => {
    const departmentId = seed.departmentSlug ? departmentBySlug.get(seed.departmentSlug) ?? null : null;
    const submittedByUserId = users[index % users.length].id;
    const slug = `seed-${slugify(seed.title)}`.slice(0, 128);

    return {
      slug,
      title: seed.title,
      orgName: seed.orgName,
      orgUrl: seed.orgUrl ?? null,
      orgLogoUrl: seed.image,
      scopeType: seed.scopeType,
      departmentId,
      sessionId: null,
      type: seed.type,
      location: seed.location,
      descriptionJson: doc(...seed.description),
      applyUrl: seed.applyUrl,
      hasInternalDetails: seed.hasInternalDetails ?? false,
      deadline: seed.deadline ? new Date(seed.deadline) : null,
      status: seed.status,
      rejectionReason: seed.rejectionReason ?? null,
      submittedByUserId,
    };
  });

  const insertedProjects = await db
    .insert(project)
    .values(projectRows)
    .onConflictDoNothing({ target: project.slug })
    .returning({ id: project.id });

  const insertedOpportunities = await db
    .insert(opportunity)
    .values(opportunityRows)
    .onConflictDoNothing({ target: opportunity.slug })
    .returning({ id: opportunity.id });

  console.log(
    JSON.stringify(
      {
        projectsSeeded: projectRows.length,
        projectsInserted: insertedProjects.length,
        opportunitiesSeeded: opportunityRows.length,
        opportunitiesInserted: insertedOpportunities.length,
      },
      null,
      2,
    ),
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
